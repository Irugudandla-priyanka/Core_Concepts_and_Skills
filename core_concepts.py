# Core Concepts and Skills - Python Practice

# 1. Variables and data types
number = 7
name = "Python"
print("Language:", name)
print("Number:", number)

# 2. Conditional statement
if number % 2 == 0:
    print("Even number")
else:
    print("Odd number")

# 3. Loop
for i in range(1, 4):
    print("Count:", i)

# 4. Function
def square(value):
    return value * value

print("Square of 4:", square(4))
